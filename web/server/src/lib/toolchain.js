'use strict';

const { execFile } = require('child_process');
const fs = require('fs/promises');
const path = require('path');

const { config } = require('../config');
const workspace = require('./workspace');
const { parseAsmOutput } = require('./parseAsm');
const { parseListing } = require('./parseListing');
const { parseEmuOutput } = require('./parseEmu');

/*
 * toolchain.js - runs the compiled C tools.
 *
 * Every invocation uses execFile with an argument ARRAY. No shell is ever
 * involved, so nothing in the user's source or filenames can be interpreted
 * as a command. Filenames are generated by this module, never taken from the
 * request body.
 */

const SOURCE_FILE = 'program.asm';
const OBJECT_FILE = 'program.o';
const LISTING_FILE = 'program.lst';

/**
 * Run a binary and resolve with its output, whatever the exit code.
 * A non-zero exit is normal here: it is how the tools report diagnostics.
 */
function runTool(binary, args, cwd) {
  return new Promise((resolve, reject) => {
    execFile(
      binary,
      args,
      {
        cwd: cwd,
        timeout: config.toolTimeoutMs,
        maxBuffer: config.maxOutputBytes,
        windowsHide: true
      },
      (err, stdout, stderr) => {
        if (err && err.code === 'ENOENT') {
          reject(
            new Error(
              'the compiled tool was not found at ' +
                binary +
                '. Run `make` in the project root first.'
            )
          );
          return;
        }
        if (err && err.killed) {
          reject(
            new Error(
              'the tool was stopped after ' +
                config.toolTimeoutMs / 1000 +
                ' seconds. The program may loop forever.'
            )
          );
          return;
        }
        if (err && /maxBuffer/i.test(String(err.message))) {
          reject(
            new Error(
              'the tool produced more output than the server will hold. ' +
                'Try turning the trace off.'
            )
          );
          return;
        }
        resolve({
          stdout: stdout == null ? '' : String(stdout),
          stderr: stderr == null ? '' : String(stderr),
          code: err && typeof err.code === 'number' ? err.code : 0
        });
      }
    );
  });
}

/* Read a file the tools may not have produced. Returns '' when absent. */
async function readIfPresent(file) {
  try {
    return await fs.readFile(file, 'utf8');
  } catch (err) {
    return '';
  }
}

/**
 * Assemble a source string.
 *
 * @param {string} source
 * @param {boolean} dumpFormat   pass -dump for the plain memory-dump listing
 * @param {boolean} keep         keep the workspace so /api/run can reuse it
 */
async function assemble(source, dumpFormat, keep) {
  const space = await workspace.create();
  const dir = space.dir;
  let cleanedUp = false;

  const cleanup = async () => {
    if (cleanedUp) {
      return;
    }
    cleanedUp = true;
    await workspace.destroy(space.id);
  };

  try {
    const sourcePath = path.join(dir, SOURCE_FILE);
    await fs.writeFile(sourcePath, source, 'utf8');

    const args = [];
    if (dumpFormat) {
      args.push('-dump');
    }
    args.push(SOURCE_FILE, OBJECT_FILE, LISTING_FILE);

    const result = await runTool(config.asmPath, args, dir);
    const parsed = parseAsmOutput(result);

    /* The assembler deliberately writes neither file when it finds an error,
     * so an empty listing on failure is expected, not a bug. */
    const listingText = parsed.success
      ? await readIfPresent(path.join(dir, LISTING_FILE))
      : '';
    const listing = parseListing(listingText, Boolean(dumpFormat));

    /* Rewrite the tool's own paths so the UI never shows a temp directory. */
    const summary = parsed.summary
      ? parsed.summary.replace(new RegExp(SOURCE_FILE, 'g'), 'program.asm')
      : '';

    const response = {
      success: parsed.success,
      errors: parsed.errors,
      warnings: parsed.warnings,
      wordCount: parsed.wordCount,
      summary: summary,
      listing: listing,
      objectFileId: null,
      stdout: result.stdout,
      stderr: result.stderr
    };

    if (parsed.success && keep) {
      response.objectFileId = space.id;
    } else {
      await cleanup();
    }
    return { response: response, dir: dir, workspaceId: space.id, cleanup: cleanup };
  } catch (err) {
    await cleanup();
    throw err;
  }
}

/**
 * Run an object file that already exists inside a workspace directory.
 *
 * @param {string} dir        workspace directory holding program.o
 * @param {object} options    { trace, dumpBefore, dumpAfter }
 */
async function run(dir, options) {
  const opts = options || {};
  const args = [];
  if (opts.trace) {
    args.push('-trace');
  }
  if (opts.dumpBefore) {
    args.push('-before');
  }
  if (opts.dumpAfter) {
    args.push('-after');
  }
  args.push(OBJECT_FILE);

  const result = await runTool(config.emuPath, args, dir);
  const parsed = parseEmuOutput(result);

  /* Cap the trace so a long run cannot flood the browser. */
  let truncated = false;
  if (parsed.trace.length > config.maxTraceSteps) {
    parsed.trace = parsed.trace.slice(0, config.maxTraceSteps);
    truncated = true;
  }
  parsed.traceTruncated = truncated;
  return parsed;
}

/* Read the object file so the UI can offer it as a download. */
async function readObject(dir) {
  return fs.readFile(path.join(dir, OBJECT_FILE));
}

async function readListing(dir) {
  return readIfPresent(path.join(dir, LISTING_FILE));
}

module.exports = {
  assemble: assemble,
  run: run,
  readObject: readObject,
  readListing: readListing,
  OBJECT_FILE: OBJECT_FILE,
  LISTING_FILE: LISTING_FILE
};
